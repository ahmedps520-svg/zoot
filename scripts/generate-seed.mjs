// Generates supabase/seed.sql from the storefront catalogue (src/js/data.js),
// so the database always starts in sync with the site.  Run: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { CONFIG, PRODUCTS } from '../src/js/data.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

const sizesFor = (type) => (type === 'set' ? [] : CONFIG.sizes);

const rows = [
  ...PRODUCTS.map((p, i) => ({ ...p, sort: (i + 1) * 10, sizes: sizesFor(p.type) })),
  {
    id: 'custom-set',
    type: 'custom',
    ref: 'studio',
    name: { ar: 'طقم زوووط مخصّص', en: 'Custom ZOOOT set' },
    sub: { ar: 'من استوديو زوووط', en: 'From the ZOOOT studio' },
    price: CONFIG.prices.set,
    imgs: [],
    swatches: [],
    sizes: [],
    sort: 999,
  },
];

const values = rows
  .map(
    (p) =>
      `  (${q(p.id)}, ${q(p.type)}, ${q(p.ref)}, ${j(p.name)}, ${j(p.sub)}, ${p.price}, ${j(p.imgs)}, ${j(p.swatches)}, ${j(p.sizes)}, ${p.sort})`,
  )
  .join(',\n');

const sql = `-- Generated by scripts/generate-seed.mjs from src/js/data.js — do not edit by hand.
-- Stock is left NULL (not tracked) so the owners can enter real counts from the dashboard.

insert into public.products (id, type, ref, name, sub, price, images, swatches, sizes, sort) values
${values}
on conflict (id) do update set
  type = excluded.type, ref = excluded.ref, name = excluded.name, sub = excluded.sub,
  images = excluded.images, swatches = excluded.swatches, sizes = excluded.sizes, sort = excluded.sort;

insert into public.settings (key, value) values
  ('public', ${j({ shipping_fee: 0, free_shipping_over: 0, whatsapp: CONFIG.whatsapp || '', payment_methods: ['cod', 'transfer'], bank_details: '' })}),
  ('notifications', ${j({ owner_email: '', status_emails: true, owner_new_order: true })})
on conflict (key) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql: ${rows.length} products`);
